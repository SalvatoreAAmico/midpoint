/* ---------------------------------------------------------------- colours
   "No raw colours outside a :root block" becomes, on iOS, "no Color(red:...)
   outside the asset catalogue". The catalogue is generated from the same
   tokens, so the two apps cannot drift apart in palette: a colour changed in
   styles.css fails this check until it is regenerated. */
{
  const css = fs.readFileSync(new URL('../styles.css', import.meta.url), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  const decls = body => Object.fromEntries([...body.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)].map(m => [m[1], m[2].trim()]));
  const dark = decls(css.match(/:root\s*\{([^}]*)\}/)[1]);
  const light = decls(css.match(/:root\[data-theme="light"\]\s*\{([^}]*)\}/)[1]);
  const rgba = v => {
    let m = v.match(/^#([0-9a-f]{3}|[0-9a-f]{6})$/i);
    if (m) { let h = m[1]; if (h.length === 3) h = [...h].map(c => c + c).join(''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16) / 255).concat(1); }
    m = v.match(/^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+))?\s*\)$/);
    if (m) return [m[1], m[2], m[3]].map(x => +x / 255).concat(m[4] === undefined ? 1 : +m[4]);
    return null;                                          // --r, --safe-b, color-scheme: not colours
  };
  const comp = ([r, g, b, a]) => ({ 'color-space': 'srgb', components: { red: r.toFixed(3), green: g.toFixed(3), blue: b.toFixed(3), alpha: a.toFixed(3) } });
  const ASSETS = new URL('../ios/MidPnt/Resources/Assets.xcassets/', import.meta.url);
  const info = { info: { author: 'xcode', version: 1 } };
  wanted.set(new URL('Contents.json', ASSETS), render(info));
  const names = [];
  for (const [k, dv] of Object.entries(dark)) {
    const d = rgba(dv), l = rgba(light[k] ?? ''); if (!d) continue;
    if (!l) throw new Error(`--${k} has no light value`);
    names.push(k);
    wanted.set(new URL(`${k}.colorset/Contents.json`, ASSETS), render({
      colors: [
        { idiom: 'universal', color: comp(l) },
        { idiom: 'universal', appearances: [{ appearance: 'luminosity', value: 'dark' }], color: comp(d) }
      ], ...info }));
  }
  // The eight route colours the people are drawn in: one set, same in either appearance.
  m.COLORS.forEach((hex, i) => {
    const c = comp(rgba(hex));
    names.push(`route-${i}`);
    wanted.set(new URL(`route-${i}.colorset/Contents.json`, ASSETS), render({ colors: [{ idiom: 'universal', color: c }], ...info }));
  });
  const camel = k => k.replace(/-(\w)/g, (_, c) => c.toUpperCase());
  wanted.set(new URL('../ios/MidPnt/Generated/Palette.swift', import.meta.url),
`// Generated by test/golden.mjs from the :root blocks of styles.css. Do not edit.
// Any/Dark colour sets live in Resources/Assets.xcassets; there is no in-app
// light/dark override on iOS (the system switch is the setting).
import SwiftUI

enum Palette {
${names.filter(k => !k.startsWith('route-')).map(k => `    static let ${camel(k)} = Color("${k}")`).join('\n')}

    /// The eight route colours, in the order people are added.
    static let route: [Color] = (0..<${m.COLORS.length}).map { Color("route-\\($0)") }
}
`);
}
for (const [name, body] of Object.entries(files)) {
  if (name !== 'catalog') wanted.set(new URL(name + '.json', GOLDEN), render(body));
}

const write = process.argv.includes('--write');
let stale = 0, total = 0;
for (const [url, text] of wanted) {
  const rel = url.pathname.slice(new URL('..', import.meta.url).pathname.length);
  total++;
  let onDisk = null;
  try { onDisk = fs.readFileSync(url, 'utf8'); } catch { /* missing counts as stale */ }
  if (onDisk === text) { console.log('  ok  ' + rel); continue; }
  if (write) {
    fs.mkdirSync(new URL('.', url), { recursive: true });
    fs.writeFileSync(url, text);
    console.log('  wrote ' + rel);
  } else {
    stale++;
    console.log('  STALE ' + rel);
  }
}

// The generated catalog is the only copy Swift reads, so it must also be
// complete: a category dropped by a bad edit would silently vanish from the app.
if (!write && stale === 0) {
  const cat = JSON.parse(fs.readFileSync(CATALOG_FILE, 'utf8'));
  if (cat.categories.length !== m.CATALOG.length) { stale++; console.log('  STALE catalog.json is missing categories'); }
}

if (stale) {
  console.log(`\n${stale} of ${total} golden files are out of date with app.js.`
    + '\nIf the change to app.js was intended: node test/golden.mjs --write,'
    + '\nthen make ios/MidPntCore agree (cd ios/MidPntCore && swift test), and commit both together.');
  process.exit(1);
}
console.log(write ? `\n${total} golden files written.` : `\n${total} golden files match app.js.`);
