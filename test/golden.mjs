/* Golden vectors: app.js is the source of truth, and ios/MidPntCore must agree.

   In a live session whichever phone taps Find decides the list for everyone.
   If the Swift scorer and the JS scorer disagree on the same inputs, the
   ranking depends on who happened to search first. So every pure function the
   app shares is run here over a fixed set of inputs, and the answers are
   written down as JSON for the Swift tests to reproduce.

     node test/golden.mjs           check: fail if the files on disk are stale
     node test/golden.mjs --write   regenerate them

   Check is the default so that this is a test, like test/migrations.sh. Change
   scoring, hours, chains or a category in app.js and this goes red until you
   regenerate; regenerate and `swift test` goes red until MidPntCore follows.
   Land both in the same commit.

   Dates are given as {day, h, m} rather than a Date, because app.js reads the
   device's local clock and a vector that depends on the machine's timezone is
   not a vector. */
